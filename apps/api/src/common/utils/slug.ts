const MAX_SLUG_LENGTH = 60;

/** Converte um nome em slug ASCII: "Vértice Consultoria" → "vertice-consultoria". */
export function slugify(value: string): string {
  const slug = value
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, MAX_SLUG_LENGTH)
    .replace(/-+$/g, '');

  return slug || 'organizacao';
}
